/**
 * Share (the right panel's Share button, File ▸ Share…): Figma UI3's share modal, as captured from live Figma
 * (docs/research/figma/live/multiplayer/README.md "Share dialog", R13-multiplayer-sharing.md §2). Two cards at the top
 * centre of the window:
 *
 * - "Share this file" · Copy link · ✕ — the invite field ("Add comma separated emails to invite": emails become chips, a
 *   role select appears inside the field, default "can view"), Invite; "Who has access": the link row ("Anyone" / "People
 *   invited to file" — opens Share settings), the owner "(you)", members with their role menus (can edit, can view,
 *   Remove); "Ask to edit" requests with Approve / Deny.
 * - Card 2: Copy Dev Mode link, More (Copy prototype link, Get embed code), Developer preview (docs/data.md §13).
 * - Share settings: Who can access, What can they do, Additional security (Password required), Advanced — applied by
 *   Save, as live Figma's.
 * - Transfer ownership: the owner picks "Owner" in a member's role menu and confirms (help.figma.com 360038512093).
 * - An org file follows its org's policy (`SharedFileInfo.policy`, docs/multiplayer.md §15.6): public links off → only
 *   "Anyone at ‹org›" and invited people; passwords required → a link anyone can open needs one; autogenerated
 *   passwords only → no field, **Generate**; links must expire → the expiry picker up to the maximum; Guest membership
 *   → a confirmation (Cancel / Share) before inviting someone outside the org, or the notices "Admin approval is
 *   required…" / "Sharing with external users is disabled…"; external content restricted → the view-only banner.
 *
 * The first invite (or Copy link) shares the file: the editor's snapshot of it goes to the room at the journal seq it
 * stands at; the store keeps it in step with the room from then on (docs/multiplayer.md §5).
 */
