const message = (e: unknown) => (e instanceof Error ? e.message : String(e));
const EMAIL = /^[^\s@,]+@[^\s@,]+\.[^\s@,]+$/;
const ROLES = [
  { value: "editor", label: "can edit" },
  { value: "viewer", label: "can view" },
];
/** The role choices in the UI's language */
const roles = () => ROLES.map((r) => ({ ...r, label: t(r.label) }));
/** A translated sentence split around one `{var}` (to put JSX there): [before, after] */
const around = (text: string, name: string): [string, string] => {
  const i = text.indexOf(`{${name}}`);
  return i < 0 ? [text, ""] : [text.slice(0, i), text.slice(i + name.length + 2)];
};
/** One email, or "N people" */
const whoOf = (list: string[]) => (list.length === 1 ? list[0] : tp(list.length, "{n} person", "{n} people"));

interface SharingSource {
  fileKey: string;
  knownHeadSeq: number;
  flush(): Promise<void>;
}

const sharingSource = (ed: EditorController): SharingSource | null => {
  const s = ed.source as unknown as Partial<SharingSource>;
  return typeof s.fileKey === "string" && typeof s.knownHeadSeq === "number" && typeof s.flush === "function" ? (s as SharingSource) : null;
};

type View = "main" | "settings" | "preview" | "embed";

/** "Copy link" → "Link copied!" for a moment (live: the text changes in place, no toast) */
function useCopied(): [boolean, () => void] {
  const [copied, setCopied] = useState(false);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(() => () => void (timer.current && clearTimeout(timer.current)), []);
  return [
    copied,
    () => {
      setCopied(true);
      if (timer.current) clearTimeout(timer.current);
      timer.current = setTimeout(() => setCopied(false), 1500);
    },
  ];
}

