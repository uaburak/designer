// The theme on the page before anything paints (docs/design-system.md §2.3, ds/theme.ts). In the desktop app the
// preference is main's (the preload's window.designer.theme, from settings.json, already resolved); in a browser it is
// the page's own ("designer-theme" in localStorage, ds/theme.ts), else the system's.
(function () {
  var desktop = window.designer && window.designer.theme;
  var dark;
  if (desktop) dark = desktop.resolved === "dark";
  else {
    var pref = null;
    try { pref = localStorage.getItem("designer-theme"); } catch (e) { /* the system's */ }
    dark = pref === "dark" || (pref !== "light" && window.matchMedia("(prefers-color-scheme: dark)").matches);
  }
  var root = document.documentElement;
  root.setAttribute("data-theme", dark ? "dark" : "light");
  // Settings › Enhance contrast (ds/theme.ts): main's in the desktop app, the page's own in a browser ("more" / "off"
  // once set, else the system's prefers-contrast).
  var contrast = false;
  if (desktop) contrast = desktop.contrast === true;
  else {
    var saved = null;
    try { saved = localStorage.getItem("designer-contrast"); } catch (e) { /* the system's */ }
    contrast = saved === "more" || (saved !== "off" && window.matchMedia("(prefers-contrast: more)").matches);
  }
  if (contrast) root.setAttribute("data-contrast", "more");
  root.style.colorScheme = dark ? "dark" : "light";
  // The page's background until the app's CSS is there: the tab bar's grey in its view, the page's white or dark elsewhere
  // — none under the tab preview card (a transparent view over the content).
  // <generated by scripts/gen-tokens.ts from ds/tokens.ts — each surface's background [light, dark]; do not edit>
  var SURFACE_BG = { app: ["#ffffff", "#2c2c2c"], tabbar: ["#e6e6e6", "#3b3b3b"], viewer: ["#f5f5f5", "#242424"] };
  // </generated>
  if (/[?&]tabpreview(=|&|$)/.test(location.search)) root.style.backgroundColor = "transparent";
  else root.style.backgroundColor = (/[?&]tabbar(=|&|$)/.test(location.search) ? SURFACE_BG.tabbar : SURFACE_BG.app)[dark ? 1 : 0];
  // A prototype on a phone (?present in a browser) starts with the UI hidden, edge to edge like a website
  // (PresentationView's `bare`): the page in its screen's colour from the first paint — the colour it had last time,
  // else white — and under the notch and the browser's bars, as Safari tints them from the first paint.
  if (!desktop && /[?&]present(=|&|$)/.test(location.search) && !/[?&]hide-ui=0/.test(location.search) && window.matchMedia("(pointer: coarse)").matches) {
    var file = (location.search.match(/[?&]file=([^&]*)/) || [])[1] || "";
    var bg = null;
    try { bg = localStorage.getItem("designer-present-bg:" + decodeURIComponent(file)); } catch (e) { /* white */ }
    if (!/^#[0-9a-f]{6}$/i.test(bg || "")) bg = "#ffffff";
    root.style.backgroundColor = bg;
    var viewport = document.querySelector('meta[name="viewport"]');
    if (viewport && !/viewport-fit/.test(viewport.content)) viewport.content += ", viewport-fit=cover";
    var theme = document.createElement("meta");
    theme.name = "theme-color";
    theme.content = bg;
    document.head.appendChild(theme);
  }
})();
