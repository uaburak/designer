// Generates throwaway keys for the SAML spike (never committed: fixtures/ and src/trust.generated.ts are git-ignored).
//   fixtures/idp.key, idp.crt          the trusted IdP (the Worker trusts idp.crt)
//   fixtures/attacker.key, attacker.crt  an untrusted signer (the "wrong certificate" and self-embedded-cert cases)
//   src/trust.generated.ts             the IdP certificate the Worker is configured with
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "fixtures");
mkdirSync(dir, { recursive: true });

for (const [name, cn] of [["idp", "Spike Test IdP"], ["attacker", "Spike Attacker"]]) {
  execFileSync("openssl", [
    "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-sha256", "-days", "30",
    "-keyout", join(dir, `${name}.key`), "-out", join(dir, `${name}.crt`), "-subj", `/CN=${cn}`,
  ], { stdio: "ignore" });
}

const cert = readFileSync(join(dir, "idp.crt"), "utf8");
writeFileSync(
  join(root, "src", "trust.generated.ts"),
  `// Generated by scripts/gen-fixtures.mjs — a throwaway test IdP certificate. Do not edit or commit.\nexport const IDP_CERT = ${JSON.stringify(cert)};\n`,
);
console.log("fixtures written to", dir);
