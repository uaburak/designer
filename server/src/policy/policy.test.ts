describe("file sharing policy in the routes (§15.6)", () => {
  it("public links off: no public or prototype link, outsiders by the link refused, embeds refused; the org link works", async () => {
    await w.run(`UPDATE files SET link_access = 'viewer' WHERE key = ?1`, WEB);
    expect((await w.call("GET", `/files/${WEB}`, w.people.olga.token)).status).toBe(200);
    expect((await w.call("GET", `/embed/${WEB}/snapshot`)).status).toBe(200);
    w.rooms.length = 0;
    await settings({ publicLinks: false });
    expect(revoked()).toEqual([WEB]);
    expect(await actions()).toContain("public_link_setting_change");
    expect((await w.call("GET", `/files/${WEB}`, w.people.olga.token)).status).toBe(404);
    expect((await w.call("GET", `/embed/${WEB}/snapshot`)).status).toBe(404);
    expect((await w.call("GET", `/embed/${WEB}`)).status).toBe(404);
    expect((await patchFile(WEB, { linkAccess: "editor" })).body.code).toBe("public_links_off");
    expect((await patchFile(WEB, { protoLinkAccess: "viewer" })).body.code).toBe("public_links_off");
    expect((await patchFile(WEB, { linkAccess: "none" })).status).toBe(200);
    expect((await patchFile(WEB, { orgLinkAccess: "viewer" })).status).toBe(200);
    // a member by the org link still opens it; GET says why the share dialog hides the public options
    const got = await w.call("GET", `/files/${WEB}`, w.people.dan.token);
    expect(got.status).toBe(200);
    expect(got.body.policy).toMatchObject({ publicLinks: false, passwordRequired: false, passwordMode: "any", linkExpiryMaxHours: null, cursorChat: true, audio: true });
    // outside orgs: no policy
    await w.call("POST", "/files", w.people.olga.token, { key: "olga_file1", name: "Mine" });
    expect((await w.call("GET", `/files/olga_file1`, w.people.olga.token)).body.policy).toBeNull();
  });

  it("passwords required: a public link needs a password, and a password can't be removed while the link is on", async () => {
    await settings({ passwordRequired: true });
    expect((await patchFile(WEB, { linkAccess: "viewer" })).body.code).toBe("password_policy");
    expect((await patchFile(WEB, { linkAccess: "viewer", linkPassword: "open sesame" })).status).toBe(200);
    expect((await patchFile(WEB, { linkPassword: null })).body.code).toBe("password_policy");
    expect((await patchFile(WEB, { linkAccess: "none", linkPassword: null })).status).toBe(200);
    // a public link without a password (set before the policy) lets nobody in by the link alone
    await w.run(`UPDATE files SET link_access = 'viewer', link_password = NULL WHERE key = ?1`, WEB);
    expect((await w.call("GET", `/files/${WEB}`, w.people.olga.token)).status).toBe(404);
    expect((await w.call("GET", `/embed/${WEB}/snapshot`)).status).toBe(404);
  });

  it("autogenerated passwords only: four generated words, nothing typed", async () => {
    await settings({ passwordMode: "autogenerated" });
    expect((await patchFile(WEB, { linkPassword: "hunter22" })).body.code).toBe("password_policy");
    expect((await patchFile(WEB, { linkPassword: generateLinkPassword() })).status).toBe(200);
    expect((await fileRow(WEB)).link_password).not.toBeNull();
    expect(await actions()).toContain("autogen_password_controls_setting_change");
  });

  it("links must expire: the maximum on PATCH, the clamp of existing links (revoked), FigJam's public links off", async () => {
    await w.run(`UPDATE files SET link_access = 'viewer', link_expires_at = NULL WHERE key = ?1`, WEB);
    await w.run(`UPDATE files SET link_access = 'viewer', link_expires_at = ?2 WHERE key = ?1`, LIB, w.now.t + 2 * HOUR);
    w.rooms.length = 0;
    await settings({ linkExpiryMaxHours: 24 });
    expect((await fileRow(WEB)).link_expires_at).toBe(w.now.t + 24 * HOUR);
    expect((await fileRow(LIB)).link_expires_at).toBe(w.now.t + 2 * HOUR); // already within
    expect(revoked().sort()).toEqual([LIB, WEB].sort());
    // lowering clamps again
    await settings({ linkExpiryMaxHours: 1 });
    expect((await fileRow(LIB)).link_expires_at).toBe(w.now.t + HOUR);
    await settings({ linkExpiryMaxHours: 24 });
    // a link opened needs an expiry within the maximum
    await w.run(`UPDATE files SET link_access = 'none', link_expires_at = NULL WHERE key = ?1`, WEB);
    expect((await patchFile(WEB, { linkAccess: "viewer" })).body.code).toBe("link_expiry_policy");
    expect((await patchFile(WEB, { linkAccess: "viewer", linkExpiresAt: w.now.t + 48 * HOUR })).body.code).toBe("link_expiry_policy");
    expect((await patchFile(WEB, { linkAccess: "viewer", linkExpiresAt: w.now.t + 12 * HOUR })).status).toBe(200);
    expect((await patchFile(WEB, { linkExpiresAt: null })).body.code).toBe("link_expiry_policy");
    expect((await patchFile(WEB, { linkExpiresAt: w.now.t + 30 * HOUR })).body.code).toBe("link_expiry_policy");
    // FigJam: links that must expire turn its public links off [F-share]
    expect((await w.call("GET", `/files/${BRAND}`, w.people.alice.token)).body.policy.publicLinks).toBe(false);
    expect((await patchFile(BRAND, { linkAccess: "viewer", linkExpiresAt: w.now.t + HOUR })).body.code).toBe("public_links_off");
  });

  it("workspace overrides: its teams' files follow them; drafts and teams outside workspaces the org's", async () => {
    expect((await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.wade.token, { sharing: { publicLinks: false } })).body.code).toBe("not_admin");
    expect((await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: { publicLinks: "no" } })).status).toBe(400);
    expect((await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: { audio: false } })).status).toBe(400);
    expect((await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: { linkExpiryMaxHours: 745 } })).status).toBe(400);
    await w.run(`UPDATE files SET link_access = 'viewer' WHERE key IN (?1, ?2)`, WEB, BRAND);
    w.rooms.length = 0;
    const r = await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: { publicLinks: false, linkExpiryMaxHours: null } });
    expect(r.body.workspace.sharing).toEqual({ publicLinks: false, linkExpiryMaxHours: null });
    expect(revoked()).toEqual([WEB]); // T2 is in W1; Brand's team isn't
    expect(await actions()).toContain("workspace_public_link_setting_change");
    expect((await w.call("GET", `/orgs/${w.orgId}/admin/workspaces`, w.people.alice.token)).body.workspaces[0].sharing).toEqual({ publicLinks: false, linkExpiryMaxHours: null });
    const policy = async (key: string, token = w.people.alice.token) => (await w.call("GET", `/files/${key}`, token)).body.policy;
    expect((await policy(WEB)).publicLinks).toBe(false);
    expect((await policy(BRAND)).publicLinks).toBe(true);
    expect((await policy(DRAFT, w.people.bob.token)).publicLinks).toBe(true);
    expect((await patchFile(WEB, { linkAccess: "editor" })).body.code).toBe("public_links_off");
    // the org turns public links off and expiry on; the workspace's overrides still win for its files
    await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: { publicLinks: true, linkExpiryMaxHours: null } });
    await settings({ publicLinks: false, linkExpiryMaxHours: 24 });
    expect(await policy(WEB)).toMatchObject({ publicLinks: true, linkExpiryMaxHours: null });
    expect(await policy(DRAFT, w.people.bob.token)).toMatchObject({ publicLinks: false, linkExpiryMaxHours: 24 });
    expect((await fileRow(WEB)).link_expires_at).toBeNull(); // not clamped: its workspace has no maximum
    expect((await patchFile(WEB, { linkAccess: "editor" })).status).toBe(200);
    expect((await patchFile(DRAFT, { linkAccess: "viewer", linkExpiresAt: w.now.t + HOUR }, w.people.bob.token)).body.code).toBe("public_links_off");
    // null clears the overrides
    expect((await w.call("PATCH", `/orgs/${w.orgId}/admin/workspaces/${W1}`, w.people.alice.token, { sharing: null })).body.workspace.sharing).toBeNull();
    expect((await policy(WEB)).publicLinks).toBe(false);
  });
});

