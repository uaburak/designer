/**
 * Sharing policies (docs/multiplayer.md §15.6) [F-share]: a file's effective policy (`filePolicy` over the org's
 * settings and its workspace's overrides), the refusals of `PATCH /files/:key`, the expiry clamp when an org (or a
 * workspace) tightens its maximum, and the revoke-link fan-out when a policy tightens.
 */
import { filePolicy, isGeneratedPassword, LINK_EXPIRY_MAX_HOURS, type FilePolicy, type WorkspaceSharingSettings } from "../../../src/shared/org/identity";
import type { EditorType, OrgSettings } from "../../../src/shared/org/types";
import { FILE_EXPORTING_LABEL, type FileExporting } from "../../../src/shared/org/governance";
import type { Deps } from "../api";
import type { D1Like } from "../db";
import { settingsOf } from "../org/db";
import { HttpError } from "../org/http";

/** The rows `filePolicy` needs of a file */
export interface PolicyFile {
  org_id: string | null;
  team_id: string | null;
  editor_type: EditorType;
}

/** A workspace's `settings.sharing` (null: none, or an empty object) */
export function sharingOf(settingsJson: string | null | undefined): WorkspaceSharingSettings | null {
  try {
    const s = JSON.parse(settingsJson ?? "{}") as { sharing?: WorkspaceSharingSettings | null };
    const w = s?.sharing;
    return w && typeof w === "object" && Object.keys(w).length ? w : null;
  } catch {
    return null;
  }
}

/** Reads cached per request (Access passes its own `once`) */
export type Once = <T>(key: string, fn: () => Promise<T>) => Promise<T>;
const noCache: Once = (_k, fn) => fn();

/** The workspace sharing overrides of a team's workspace (drafts and teams outside workspaces: null — the org's) */
export async function teamSharing(d1: D1Like, teamId: string | null, once: Once = noCache): Promise<WorkspaceSharingSettings | null> {
  if (!teamId) return null;
  return once(`ws-sharing:${teamId}`, async () => {
    const r = await d1.prepare(`SELECT w.settings FROM teams t JOIN workspaces w ON w.id = t.workspace_id WHERE t.id = ?1`).bind(teamId).first<{ settings: string }>();
    return r ? sharingOf(r.settings) : null;
  });
}

/** The file's effective policy (`GET /files/:key` → `policy`); null outside orgs */
export async function policyOfFile(d1: D1Like, f: PolicyFile, once: Once = noCache): Promise<FilePolicy | null> {
  if (!f.org_id) return null;
  const orgId = f.org_id;
  const org = await once(`org-settings:${orgId}`, async () => {
    const r = await d1.prepare(`SELECT settings, governance_plus FROM orgs WHERE id = ?1`).bind(orgId).first<{ settings: string; governance_plus: number }>();
    return { settings: settingsOf(r), governancePlus: !!r?.governance_plus };
  });
  const ws = await teamSharing(d1, f.team_id, once);
  const p = filePolicy(org.settings, ws, f.editor_type);
  // File exporting (docs/governance.md §2.7): with Governance+ only; the workspace's setting overrides the org's.
  return org.governancePlus ? { ...p, fileExporting: ws?.fileExporting ?? org.settings.fileExporting } : p;
}

export interface FilePatch {
  linkAccess?: unknown;
  protoLinkAccess?: unknown;
  linkPassword?: unknown;
  linkExpiresAt?: unknown;
}

/**
 * `PATCH /files/:key`'s refusals by policy, checked before anything is written (§15.6):
 * - public links off → `linkAccess` / `protoLinkAccess` other than none: 403 `public_links_off`;
 * - passwords required → a public link on a file without a password, or removing the password of a file with one:
 *   400 `password_policy`;
 * - autogenerated passwords only → a password `isGeneratedPassword` refuses: 400 `password_policy`;
 * - links must expire → a public link whose expiry (this patch's or the file's) is absent or past the maximum: 400
 *   `link_expiry_policy`.
 */
export function checkFilePatch(policy: FilePolicy | null, f: { link_access: string; link_password: string | null; link_expires_at: number | null }, body: FilePatch, now: number): void {
  if (!policy) return;
  const linkAfter = body.linkAccess !== undefined ? body.linkAccess : f.link_access;
  const hasPasswordAfter = body.linkPassword !== undefined ? body.linkPassword !== null : f.link_password !== null;
  const opening = body.linkAccess !== undefined && body.linkAccess !== "none";
  if (!policy.publicLinks) {
    if (opening) throw new HttpError(403, "your organization turned off public link sharing", "public_links_off");
    if (body.protoLinkAccess !== undefined && body.protoLinkAccess !== "none") throw new HttpError(403, "your organization turned off public link sharing", "public_links_off");
  }
  if (typeof body.linkPassword === "string" && policy.passwordMode === "autogenerated" && !isGeneratedPassword(body.linkPassword)) throw new HttpError(400, "your organization only allows autogenerated passwords", "password_policy");
  if (policy.passwordRequired && linkAfter !== "none" && !hasPasswordAfter && (opening || body.linkPassword === null)) throw new HttpError(400, "your organization requires a password for links anyone can open", "password_policy");
  if (policy.linkExpiryMaxHours !== null && opening) {
    const at = body.linkExpiresAt !== undefined ? body.linkExpiresAt : f.link_expires_at;
    const max = now + policy.linkExpiryMaxHours * 3_600_000;
    if (typeof at !== "number" || !Number.isFinite(at) || at <= now || at > max) throw new HttpError(400, `links anyone can open must expire within ${policy.linkExpiryMaxHours} hours`, "link_expiry_policy", { maxHours: policy.linkExpiryMaxHours });
  }
}

/** `linkExpiresAt` alone, against the maximum (a file whose public link stays on) */
export function checkExpiry(policy: FilePolicy | null, at: number | null, now: number): void {
  if (!policy || policy.linkExpiryMaxHours === null) return;
  if (at === null || at > now + policy.linkExpiryMaxHours * 3_600_000) throw new HttpError(400, `links in this organization expire within ${policy.linkExpiryMaxHours} hours`, "link_expiry_policy", { maxHours: policy.linkExpiryMaxHours });
}

/** `linkExpiryMaxHours`: null or a whole number of hours, 1…744 (Figma: 1 hour to 31 days) */
export const validMaxHours = (v: unknown): boolean => v === null || (typeof v === "number" && Number.isInteger(v) && v >= 1 && v <= LINK_EXPIRY_MAX_HOURS);

/** `{sharing}` of `PATCH admin/workspaces/:id`, validated (null or {}: no overrides) */
export function cleanWorkspaceSharing(v: unknown): WorkspaceSharingSettings | null {
  if (v === null) return null;
  if (!v || typeof v !== "object" || Array.isArray(v)) throw new HttpError(400, "sharing is an object or null");
  const s = v as Record<string, unknown>;
  const out: WorkspaceSharingSettings = {};
  for (const k of Object.keys(s)) if (k !== "publicLinks" && k !== "passwordRequired" && k !== "linkExpiryMaxHours" && k !== "fileExporting") throw new HttpError(400, `sharing.${k} isn't a workspace setting`);
  // Round 14 (docs/governance.md §2.7): Custom settings for workspaces › File exporting
  if (s.fileExporting !== undefined) {
    if (typeof s.fileExporting !== "string" || !(s.fileExporting in FILE_EXPORTING_LABEL)) throw new HttpError(400, "sharing.fileExporting is all, guests_blocked or viewers_blocked");
    out.fileExporting = s.fileExporting as FileExporting;
  }
  if (s.publicLinks !== undefined) {
    if (typeof s.publicLinks !== "boolean") throw new HttpError(400, "sharing.publicLinks");
    out.publicLinks = s.publicLinks;
  }
  if (s.passwordRequired !== undefined) {
    if (typeof s.passwordRequired !== "boolean") throw new HttpError(400, "sharing.passwordRequired");
    out.passwordRequired = s.passwordRequired;
  }
  if (s.linkExpiryMaxHours !== undefined) {
    if (!validMaxHours(s.linkExpiryMaxHours)) throw new HttpError(400, "sharing.linkExpiryMaxHours is null or 1–744 hours");
    out.linkExpiryMaxHours = s.linkExpiryMaxHours as number | null;
  }
  return Object.keys(out).length ? out : null;
}

/** Does the change from `a` to `b` close anything a public link opened? (the rooms then reauth link-only people) */
export function tightened(a: Pick<FilePolicy, "publicLinks" | "passwordRequired" | "linkExpiryMaxHours">, b: Pick<FilePolicy, "publicLinks" | "passwordRequired" | "linkExpiryMaxHours">): boolean {
  return (a.publicLinks && !b.publicLinks) || (!a.passwordRequired && b.passwordRequired) || (b.linkExpiryMaxHours !== null && (a.linkExpiryMaxHours === null || b.linkExpiryMaxHours < a.linkExpiryMaxHours));
}

interface LinkFile {
  key: string;
  team_id: string | null;
  editor_type: EditorType;
  link_expires_at: number | null;
}

/**
 * After an org's (or a workspace's) sharing settings changed: every org file with a public link gets its expiry
 * clamped to its effective maximum (`min(link_expires_at, now + max)`), and — when the policy tightened — its room
 * reauthorizes link-only people (`POST /room/revoke-link`). `teamIds` limits it to a workspace's teams.
 */
export async function applySharingChange(deps: Deps, orgId: string, opts: { tightened: boolean; teamIds?: string[] }): Promise<{ clamped: string[]; revoked: string[] }> {
  const d1 = deps.db.d1;
  const now = deps.now();
  const { results } = await d1
    .prepare(`SELECT key, team_id, editor_type, link_expires_at FROM files WHERE org_id = ?1 AND (link_access <> 'none' OR proto_link_access <> 'none')`)
    .bind(orgId)
    .all<LinkFile>();
  const settings: OrgSettings = settingsOf(await d1.prepare(`SELECT settings FROM orgs WHERE id = ?1`).bind(orgId).first<{ settings: string }>());
  const cache = new Map<string, Promise<unknown>>();
  const once: Once = (k, fn) => {
    let p = cache.get(k);
    if (!p) cache.set(k, (p = fn()));
    return p as never;
  };
  const clamped: string[] = [];
  const revoked: string[] = [];
  for (const f of results) {
    if (opts.teamIds && (!f.team_id || !opts.teamIds.includes(f.team_id))) continue;
    const p = filePolicy(settings, await teamSharing(d1, f.team_id, once), f.editor_type);
    if (p.linkExpiryMaxHours !== null) {
      const cap = now + p.linkExpiryMaxHours * 3_600_000;
      if (f.link_expires_at === null || f.link_expires_at > cap) {
        await d1.prepare(`UPDATE files SET link_expires_at = ?2 WHERE key = ?1`).bind(f.key, cap).run();
        clamped.push(f.key);
      }
    }
    if (opts.tightened || clamped.includes(f.key)) {
      revoked.push(f.key);
      try {
        await deps.rooms.fetch(f.key, "/room/revoke-link", { method: "POST" });
      } catch (e) {
        console.error("sharing: room not told", f.key, e);
      }
    }
  }
  return { clamped, revoked };
}
