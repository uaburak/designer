// The SAML SP's Node libraries (@node-saml/node-saml, @xmldom/xmldom and what they pull in: xpath, xmlbuilder,
// xml-crypto…) as one ES module of their own, `src/samlVendor.gen.mjs` — about 1.2 MB of the Worker's 2.2 MB. Wrangler
// uploads it unbundled (wrangler.jsonc `find_additional_modules` + `rules`), and the Worker imports it only on a SAML
// route (src/auth/saml/lib.js `loadSamlLib`): every other request's isolate never parses it, which halves the Worker's
// startup (docs/multiplayer.md §17, "CPU per request"). Run by wrangler before every build (`build.command`).
import { createRequire } from "node:module";
import { builtinModules } from "node:module";
import { fileURLToPath, URL } from "node:url";

// esbuild as wrangler's own (same version as the Worker's bundle)
const require = createRequire(createRequire(import.meta.url).resolve("wrangler/package.json"));
const esbuild = require("esbuild");

const builtins = new Set(builtinModules.flatMap((m) => [m, `node:${m}`]));

await esbuild.build({
  entryPoints: [fileURLToPath(new URL("../src/auth/saml/vendor.js", import.meta.url))],
  outfile: fileURLToPath(new URL("../src/samlVendor.gen.mjs", import.meta.url)),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  // As wrangler resolves packages for the Worker
  mainFields: ["browser", "module", "main"],
  conditions: ["workerd", "worker", "browser"],
  minify: true,
  legalComments: "none",
  logLevel: "warning",
  banner: { js: "// Generated by server/scripts/build-saml.mjs — do not edit." },
  plugins: [
    {
      // Node's built-ins (nodejs_compat): `require("zlib")` in a CommonJS dependency becomes an import of the runtime's
      // module, as wrangler's own bundling does
      name: "node-builtins",
      setup(b) {
        b.onResolve({ filter: /.*/ }, (a) => {
          if (!builtins.has(a.path)) return undefined;
          return a.kind === "require-call" ? { path: a.path, namespace: "builtin" } : { path: a.path, external: true };
        });
        b.onLoad({ filter: /.*/, namespace: "builtin" }, (a) => ({ contents: `import m from ${JSON.stringify(a.path)}; module.exports = m;`, loader: "js" }));
      },
    },
  ],
});
