/**
 * Figma's canvas cursors as a TS table (src/renderer/src/engine/cursors.ts draws from it):
 *
 *   src/renderer/src/engine/cursorArt/svg/cursor-<name>.svg + hotspots.json
 *     →  src/renderer/src/engine/cursorArt/figmaCursors.generated.ts
 *
 *   npm run cursors              write the table
 *   npm run cursors -- --check   exit 1 if the table is not what the SVGs give
 *
 * Where the art comes from (docs/research/chrome-cursors/README.md): Figma's fullscreen wasm keeps each cursor as a
 * compiled vector resource ("cursor-*.svg": paths with white and black fills), and its code gives each a 32 × 32 box
 * and a hot spot; the SVGs here are those resources decoded, not redrawn. Figma's art — for this personal app only, do
 * not redistribute.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(root, "src/renderer/src/engine/cursorArt");
const OUT = join(DIR, "figmaCursors.generated.ts");

export function generate(): string {
  const hot = JSON.parse(readFileSync(join(DIR, "hotspots.json"), "utf8")) as Record<string, [number, number]>;
  const rows: string[] = [];
  for (const file of readdirSync(join(DIR, "svg")).filter((f) => f.endsWith(".svg")).sort()) {
    const name = file.replace(/^cursor-/, "").replace(/\.svg$/, "");
    const svg = readFileSync(join(DIR, "svg", file), "utf8").trim();
    const open = /<svg\b[^>]*>/.exec(svg)?.[0] ?? "";
    const w = Number(/\swidth="([\d.]+)"/.exec(open)?.[1]);
    const h = Number(/\sheight="([\d.]+)"/.exec(open)?.[1]);
    const body = svg.slice(open.length, svg.lastIndexOf("</svg>"));
    const spot = hot[name];
    if (!spot) throw new Error(`hotspots.json has no hot spot for ${name}`);
    rows.push(`  ${JSON.stringify(name)}: { w: ${w}, h: ${h}, hot: [${spot[0]}, ${spot[1]}], body: ${JSON.stringify(body)} },`);
  }
  return [
    "/**",
    " * GENERATED by scripts/gen-cursors.ts from engine/cursorArt/svg + hotspots.json — do not edit; `npm run cursors`.",
    " * Figma's canvas cursors (UI3), decoded from the resources of Figma's fullscreen wasm (docs/research/chrome-cursors/",
    " * README.md): the art's box (w × h, CSS px at 1×), the hot spot Figma's code gives it, and the SVG's content. Figma's",
    " * art — for this personal app only, do not redistribute.",
    " */",
    "export interface FigmaCursor {",
    "  w: number;",
    "  h: number;",
    "  hot: readonly [number, number];",
    "  body: string;",
    "}",
    "",
    "export const FIGMA_CURSORS = {",
    ...rows,
    "} as const satisfies Record<string, FigmaCursor>;",
    "",
    "export type FigmaCursorName = keyof typeof FIGMA_CURSORS;",
    "",
  ].join("\n");
}

const text = generate();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (current !== text) {
    console.error("figmaCursors.generated.ts is out of date: npm run cursors");
    process.exit(1);
  }
} else writeFileSync(OUT, text);
