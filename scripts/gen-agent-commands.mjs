// Generates src/renderer/src/editor/agents/engineCommands.generated.ts: the engine's commands (CommandId in
// engine/src/editor/Commands.h) with the argument shapes their comments give — run_command / list_commands' table.
import { readFileSync, writeFileSync } from "node:fs";
const h = readFileSync("engine/src/editor/Commands.h", "utf8");
const body = h.slice(h.indexOf("enum class CommandId"), h.indexOf("};", h.indexOf("enum class CommandId")));
const out = {};
for (const line of body.split("\n")) {
  const m = /^\s*([A-Z0-9_]+)\s*=\s*\d+,?\s*(?:\/\/\s*(.*))?$/.exec(line);
  if (m) out[m[1]] = (m[2] ?? "").trim();
}
writeFileSync("src/renderer/src/editor/agents/engineCommands.generated.ts", `// GENERATED by scripts/gen-agent-commands.mjs from engine/src/editor/Commands.h. Do not edit.\n/** The engine's commands and their argument shapes (refs?: the selection when absent). */\nexport const ENGINE_COMMAND_DOCS: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, "commands");
