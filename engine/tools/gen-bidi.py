#!/usr/bin/env python3
"""Generates engine/src/text/BidiClass.generated.h: every code point's Bidi_Class (UAX #9) as ranges, from Python's
own Unicode database (unicodedata.bidirectional), with DerivedBidiClass.txt's defaults for unassigned code points
(R for the Hebrew / N'Ko / … blocks, AL for the Arabic ones, ET for currency symbols, BN for noncharacters and
default ignorables; L otherwise). Code points not listed are L.

    python3 engine/tools/gen-bidi.py      (Python ≥ 3.12 for Unicode 15)
"""
import os
import sys
import unicodedata

CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
           "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]

# DerivedBidiClass.txt's @missing lines (Unicode 15).
DEFAULTS = [
    (0x0590, 0x05FF, "R"), (0x0600, 0x07BF, "AL"), (0x07C0, 0x085F, "R"), (0x0860, 0x08FF, "AL"),
    (0x20A0, 0x20CF, "ET"), (0xFB1D, 0xFB4F, "R"), (0xFB50, 0xFDCF, "AL"), (0xFDF0, 0xFDFF, "AL"),
    (0xFE70, 0xFEFF, "AL"), (0x10800, 0x10CFF, "R"), (0x10D00, 0x10D3F, "AL"), (0x10D40, 0x10EBF, "R"),
    (0x10EC0, 0x10EFF, "AL"), (0x10F00, 0x10F2F, "R"), (0x10F30, 0x10F6F, "AL"), (0x10F70, 0x10FFF, "R"),
    (0x1E800, 0x1EC6F, "R"), (0x1EC70, 0x1ECBF, "AL"), (0x1ECC0, 0x1ECFF, "R"), (0x1ED00, 0x1ED4F, "AL"),
    (0x1ED50, 0x1EDFF, "R"), (0x1EE00, 0x1EEFF, "AL"), (0x1EF00, 0x1EFFF, "R"),
]


def default_of(cp):
    if (cp & 0xFFFE) == 0xFFFE or 0xFDD0 <= cp <= 0xFDEF:
        return "BN"
    if 0xE0000 <= cp <= 0xE0FFF or 0x2060 <= cp <= 0x206F or 0xFFF0 <= cp <= 0xFFF8:
        return "BN"
    for start, end, c in DEFAULTS:
        if start <= cp <= end:
            return c
    return "L"


def bidi_class(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return "L"
    c = unicodedata.bidirectional(chr(cp))
    return c if c else default_of(cp)


ranges = []
for cp in range(0x110000):
    c = bidi_class(cp)
    if ranges and ranges[-1][2] == c and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, c])
ranges = [r for r in ranges if r[2] != "L"]

lines = []
row = []
for start, end, c in ranges:
    row.append("{0x%X, 0x%X, %s}" % (start, end, c))
    if len(row) == 4:
        lines.append("    " + ", ".join(row) + ",")
        row = []
if row:
    lines.append("    " + ", ".join(row) + ",")

body = f"""// Generated by engine/tools/gen-bidi.py (Unicode {unicodedata.unidata_version}). Do not edit.
// Bidi_Class (UAX #9) as ranges start..end, sorted; code points in none of them are L.
#pragma once

#include <cstdint>

namespace eng::text {{

enum class BidiClass : uint8_t {{ {", ".join(CLASSES)} }};

struct BidiRange {{
  uint32_t start, end;
  BidiClass cls;
}};

namespace bidi_table {{
using enum BidiClass;
inline constexpr BidiRange kRanges[] = {{
{chr(10).join(lines)}
}};
}}  // namespace bidi_table

}}  // namespace eng::text
"""
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "text", "BidiClass.generated.h")
open(path, "w").write(body)
print(f"bidi: Unicode {unicodedata.unidata_version}, {len(ranges)} ranges", file=sys.stderr)
